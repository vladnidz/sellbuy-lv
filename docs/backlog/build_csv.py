import csv, re, json
ns={}
exec(open('_part1.py',encoding='utf-8').read(), ns)
exec(open('_part2.py',encoding='utf-8').read(), ns)
rows = ns['S1'] + ns['S2']
cols = ['id','epic','release','priority','size','title','acceptance_criteria','technical_tasks','tests','depends_on','events']
ids = [r[0] for r in rows]
assert len(ids)==len(set(ids)), 'duplicate ids'
valid_rel={'R1','R2','R3','R4','R5'}
valid_pri={'Must','Should','Could','Won\'t'}
valid_size={'XS','S','M','L','XL'}
errors=[]
for r in rows:
    rid,epic,rel,pri,size,title,ac,tech,tests,deps,events = r
    if rel not in valid_rel: errors.append((rid,'release',rel))
    if pri not in valid_pri: errors.append((rid,'priority',pri))
    if size not in valid_size: errors.append((rid,'size',size))
    for d in [x.strip() for x in deps.split(',') if x.strip()]:
        if re.match(r'^US-\d\d\.\d\d$', d) and d not in ids:
            errors.append((rid,'missing dependency',d))
    if not ac.strip() or not tech.strip() or not tests.strip():
        errors.append((rid,'empty field',''))
print('stories:', len(rows))
print('errors:', errors if errors else 'none')
# counts by release and epic
from collections import Counter
print(Counter(r[2] for r in rows))
print(Counter(r[1] for r in rows))
with open('stories.csv','w',newline='',encoding='utf-8') as f:
    w=csv.writer(f, quoting=csv.QUOTE_MINIMAL)
    w.writerow(cols)
    for r in rows:
        w.writerow(list(r))
print('written stories.csv')

# Readable markdown rendering
EPICS = {
 'EP-00':'Foundation and platform','EP-01':'Identity, accounts and profiles','EP-02':'Category tree and attributes',
 'EP-03':'Listings','EP-04':'Search and discovery','EP-05':'Messaging and negotiation','EP-06':'Trust and safety',
 'EP-07':'Payments, escrow and fees','EP-08':'Logistics and delivery','EP-09':'Auctions','EP-10':'Business marketplace',
 'EP-11':'Seller tools and monetisation','EP-12':'Price intelligence and AI','EP-13':'Admin and operations',
 'EP-14':'Notifications and communications','EP-15':'Legal, compliance and privacy','EP-16':'Growth, SEO and mobile'}
out=['# SellBuy.lv — Full backlog (generated from stories.csv)','',
     'Generated by build_csv.py. Edit stories.csv, then rerun the script. Do not edit this file by hand.','',
     f'Total stories: {len(rows)}. Releases: ' + ', '.join(f"{k} {v}" for k,v in sorted(Counter(r[2] for r in rows).items())) + '.','']
out.append('## Index')
out.append('')
out.append('| Epic | Name | Stories |')
out.append('|---|---|---|')
cnt=Counter(r[1] for r in rows)
for e in EPICS:
    out.append(f'| {e} | {EPICS[e]} | {cnt[e]} |')
out.append('')
cur=None
for r in rows:
    rid,epic,rel,pri,size,title,ac,tech,tests,deps,events = r
    if epic!=cur:
        cur=epic
        out += ['', f'## {epic} · {EPICS[epic]}', '']
    out.append(f'### {rid} · {title}')
    out.append('')
    out.append(f'Release **{rel}** · Priority **{pri}** · Size **{size}** · Epic {epic}')
    out.append('')
    out.append('**Acceptance criteria**')
    out += [f'- {x.strip()}' for x in ac.split(';') if x.strip()]
    out.append('')
    out.append('**Technical tasks**')
    out += [f'- {x.strip()}' for x in tech.split(';') if x.strip()]
    out.append('')
    out.append(f'**Tests:** {tests}')
    out.append('')
    out.append('**Depends on:** ' + (deps if deps else 'none'))
    if events:
        out.append('')
        out.append('**Events:** ' + events)
    out.append('')
open('BACKLOG.md','w',encoding='utf-8').write('\n'.join(out)+'\n')
print('BACKLOG.md lines:', len(out))
